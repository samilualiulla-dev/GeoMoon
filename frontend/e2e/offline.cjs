const { chromium } = require('playwright')
const S = process.env.E2E_OUT || '.e2e-out'; require('fs').mkdirSync(S + '/shots', { recursive: true })
;(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
  const out = []; const ok = (n, c, x = '') => { out.push(c); console.log((c ? 'PASS ' : 'FAIL ') + n + (x ? ' — ' + x : '')) }
  await p.goto((process.env.E2E_BASE || 'http://127.0.0.1:5173') + '/'); await p.waitForTimeout(2500)
  const body = () => p.textContent('body')
  ok('dashboard: offline banner', /Computational core unreachable/.test(await body()) && /Cannot reach the GeoMoon core/.test(await body()))
  ok('dashboard: no invented stats', /Missions\s*—/.test((await body()).replace(/\s+/g, ' ')) || /—/.test(await p.textContent('[data-testid="counts"]')))
  await p.click('text=Terrain Analysis'); await p.fill('[data-testid="f-radius_m"]', '1000'); await p.click('[data-testid="run-analysis"]')
  await p.waitForSelector('[role="alert"]', { timeout: 15000 })
  ok('terrain: server-connection error shown', /Cannot reach/.test(await p.textContent('[role="alert"]')))
  ok('terrain: no results fabricated', await p.locator('[data-testid="summary"]').count() === 0)
  await p.click('text=Data Sources'); await p.waitForSelector('[role="alert"]', { timeout: 15000 }); ok('data sources: error shown', true)
  await p.click('text=Landing Simulation'); await p.waitForTimeout(1500)
  await p.click('[data-testid="start"]'); await p.waitForSelector('[role="alert"]', { timeout: 15000 })
  ok('simulation: no result without core', await p.locator('[data-testid="result-summary"]').count() === 0)
  await p.screenshot({ path: S + '/shots/12-offline.png' })
  await b.close(); process.exit(out.every(Boolean) ? 0 : 1)
})()
